/** The files to write, by their path in src/node/. */
export function generated(): Map<string, string> {
  const files = new Map<string, string>();
  for (const name of unenvModules()) {
    if (handWritten.has(name)) continue;
    const code =
      own[name]?.() ??
      `${header}
// \`node:${name}\` of Node.js, as unenv has it in a browser.
export * from "unenv/node/${name}";
export { default } from "unenv/node/${name}";
`;
    files.set(`${name}.ts`, code);
  }
  return files;
}

/** The files in src/node/ but the hand-written ones, by their path there. */
export function written(): Map<string, string> {
  const files = new Map<string, string>();
  const walk = (dir: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(file);
      else if (entry.name.endsWith(".ts")) {
        const name = path.relative(outputDir, file).split(path.sep).join("/");
        if (!handWritten.has(name.slice(0, -".ts".length))) {
          files.set(name, fs.readFileSync(file, "utf8"));
        }
      }
    }
  };
  if (fs.existsSync(outputDir)) walk(outputDir);
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = generated();
  // A module unenv no longer has.
  for (const file of written().keys()) {
    if (!files.has(file)) fs.rmSync(path.join(outputDir, file));
  }
  for (const [file, code] of files) {
    fs.mkdirSync(path.dirname(path.join(outputDir, file)), { recursive: true });
    fs.writeFileSync(path.join(outputDir, file), code);
  }
  console.log(`${files.size} modules in ${outputDir}`);
}
