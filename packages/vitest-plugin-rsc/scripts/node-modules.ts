/** The modules unenv stands in for, like "fs" and "fs/promises". */
export function unenvModules(): string[] {
  const names: string[] = [];
  const walk = (dir: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (entry.name !== "internal") walk(path.join(dir, entry.name));
      } else if (entry.name.endsWith(".mjs")) {
        const file = path.relative(unenvDir, path.join(dir, entry.name)).slice(0, -".mjs".length);
        names.push(file.split(path.sep).join("/"));
      }
    }
  };
  walk(unenvDir);
  return names.filter((name) => !notHere.has(name)).sort();
}

// A node of the AST, by its `type`.
type Pattern = ESTree.Node & { [key: string]: any };

// The names a pattern of a declaration binds, like `export const { a, b } = c`.
function namesOf(pattern: Pattern | null): string[] {
  switch (pattern?.type) {
    case "Identifier":
      return [pattern.name];
    case "ObjectPattern":
      return pattern.properties.flatMap((property: Pattern) =>
        namesOf(property.type === "RestElement" ? property.argument : property.value),
      );
    case "ArrayPattern":
      return pattern.elements.flatMap(namesOf);
    case "AssignmentPattern":
      return namesOf(pattern.left);
    case "RestElement":
      return namesOf(pattern.argument);
    default:
      return [];
  }
}

// An exported name: an identifier, or a string, as `export { a as "b" }`.
const nameOf = (exported: { name?: string; value?: unknown }): string =>
  exported.name ?? String(exported.value);

// The named exports of a file of unenv, read from its code: unenv's own
// `process` touches the process it runs in as it is evaluated.
function exportsOfFile(file: string): string[] {
  const names: string[] = [];
  for (const node of parseAst(fs.readFileSync(file, "utf8")).body as Pattern[]) {
    if (node.type === "ExportNamedDeclaration") {
      const { declaration } = node;
      if (declaration?.type === "VariableDeclaration") {
        names.push(...declaration.declarations.flatMap((each: Pattern) => namesOf(each.id)));
      } else if (declaration?.id) {
        names.push(nameOf(declaration.id as { name?: string }));
      }
      for (const specifier of node.specifiers) names.push(nameOf(specifier.exported));
    } else if (node.type === "ExportAllDeclaration") {
      if (node.exported) names.push(nameOf(node.exported));
      else if (node.source.value.startsWith(".")) {
        names.push(...exportsOfFile(path.resolve(path.dirname(file), node.source.value)));
      } else {
        // Its names would be missing here, and so in the module.
        throw new Error(`${file} re-exports ${node.source.value}`);
      }
    }
  }
  return [...new Set(names)].filter((name) => name !== "default");
}

/** The named exports of unenv's stand-in for a module of Node.js. */
export const exportsOf = (name: string): string[] =>
  exportsOfFile(path.join(unenvDir, `${name}.mjs`));

